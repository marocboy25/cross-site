/** A token's logo, or the Cross mark for CROSS. Unknown symbols render nothing. */
export function TokenLogo({ symbol, ...props }: { symbol: string } & SVGProps<SVGSVGElement>) {
  if (symbol === 'CROSS') {
    // The mark's bounds inside its square, so it fills the box like the others.
    return (
      <svg viewBox="250 250 754 754" fill="currentColor" aria-hidden="true" {...props}>
        {MARK_PATHS.map((d) => (
          <path key={d} d={d} />
        ))}
      </svg>
    )
  }
  const d = PATHS[symbol]
  if (!d) return null
  return (
    <svg viewBox="0 0 24 24" fill="currentColor" aria-hidden="true" {...props}>
      <path d={d} />
    </svg>
  )
}
